fn main() {
    for key in ["SS_UPDATE_PUBLIC_KEY", "SS_UPDATE_ENDPOINT"] {
        println!("cargo:rerun-if-env-changed={key}");
        println!(
            "cargo:rustc-env={key}={}",
            std::env::var(key).unwrap_or_default()
        );
    }
    println!("cargo:rerun-if-env-changed=SS_BUILD_IDENTITY");
    println!("cargo:rerun-if-env-changed=TAURI_CONFIG");
    println!("cargo:rerun-if-changed=tauri.conf.json");
    let target = std::env::var("TARGET").expect("Cargo provides TARGET");
    let config: serde_json::Value = serde_json::from_str(
        &std::fs::read_to_string("tauri.conf.json").expect("read Tauri config"),
    )
    .expect("valid Tauri config");
    let overrides: serde_json::Value =
        serde_json::from_str(&std::env::var("TAURI_CONFIG").unwrap_or_else(|_| "{}".to_owned()))
            .expect("valid Tauri config overrides");
    // Installer versions can change independently of internal workspace crates.
    let version = overrides
        .get("version")
        .or_else(|| config.get("version"))
        .and_then(serde_json::Value::as_str)
        .expect("Tauri config supplies the application version");
    let identity = std::env::var("SS_BUILD_IDENTITY").map_or_else(
        |_| {
            serde_json::json!({
                "schemaVersion": 1, "channel": "development", "version": version,
                "commit": "unknown", "dirty": true, "target": target,
                "origin": "local", "profile": std::env::var("PROFILE").unwrap_or_default()
            })
        },
        |value| {
            let identity: serde_json::Value = serde_json::from_str(&value)
                .expect("SS_BUILD_IDENTITY must be JSON generated by the test-build script");
            assert_eq!(identity["target"], target, "build identity target mismatch");
            assert_eq!(
                identity["version"], version,
                "build identity version mismatch"
            );
            identity
        },
    );
    let output =
        std::path::PathBuf::from(std::env::var_os("OUT_DIR").expect("Cargo provides OUT_DIR"));
    std::fs::write(output.join("build-identity.json"), identity.to_string())
        .expect("write build identity");
    tauri_build::build()
}
