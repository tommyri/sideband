#!/usr/bin/env python3
"""Generate the dependency graph and waves in docs/plan/tasks/INDEX.md.

The task tables in INDEX.md are the source. Every row there names one task,
its dependencies and its status. This script rewrites the Mermaid graph and
the waves table between their `plan-index` markers, and with `--check` fails
instead of writing when they are stale. It also fails when a row disagrees
with its task file (`Status:` or `Depends on:`), names an unknown task, uses
an unknown status, marks a task `done` while a dependency is not merged
(`done` or `awaiting-acceptance`), leaves an `awaiting-acceptance` task out
of ACCEPTANCE.md, or the dependencies form a cycle.

Run: python3 scripts/plan-index.py [--check] [--index PATH]
Tests: python3 scripts/plan-index.test.py
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
import re
import sys

STATUSES = ("todo", "in-progress", "awaiting-acceptance", "done", "blocked")
# Code merged: a done task may depend on these.
MERGED = ("awaiting-acceptance", "done")
DEFAULT_INDEX = Path(__file__).resolve().parent.parent / "docs/plan/tasks/INDEX.md"
ACCEPTANCE = "ACCEPTANCE.md"  # next to INDEX.md
GRAPH = "graph"
WAVES = "waves"
NOTICE = "Generated by `scripts/plan-index.py` from the tables above; run `just plan-index`."

_ID = re.compile(r"T-\d{3}[A-Z]?")
_LINK = re.compile(r"^\[(T-\d{3}[A-Z]?)\]\(([^)]+)\)$")


class PlanError(Exception):
    """The index cannot be generated or is stale."""


@dataclass(frozen=True)
class Task:
    id: str
    file: str
    deps: tuple[str, ...]
    status: str


def sort_key(task_id: str) -> tuple[int, str]:
    """T-045 < T-045A < T-045B < T-046."""
    return int(task_id[2:5]), task_id[5:]


def _cells(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _deps(cell: str) -> tuple[str, ...]:
    cell = cell.strip()
    if cell in {"", "—", "-", "–"}:
        return ()
    found = _ID.findall(cell)
    rest = _ID.sub("", cell).replace(",", "").strip()
    if not found or rest:
        raise PlanError(f"cannot read dependencies {cell!r}")
    return tuple(found)


def parse_tasks(text: str) -> list[Task]:
    """Rows of every table whose header has `ID`, `Depends on` and `Status`."""
    tasks: list[Task] = []
    columns: dict[str, int] | None = None
    previous = ""
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped.startswith("|"):
            columns = None
            previous = ""
            continue
        cells = _cells(stripped)
        if columns is None:
            if set(cells) >= {"ID", "Depends on", "Status"}:
                columns = {name: i for i, name in enumerate(cells)}
            previous = stripped
            continue
        if previous and set(stripped) <= set("|-: "):
            previous = ""
            continue
        if len(cells) < len(columns):
            raise PlanError(f"short table row: {stripped}")
        link = _LINK.match(cells[columns["ID"]])
        if not link:
            raise PlanError(f"row does not start with a task link: {stripped}")
        tasks.append(Task(
            id=link.group(1),
            file=link.group(2),
            deps=_deps(cells[columns["Depends on"]]),
            status=cells[columns["Status"]],
        ))
    return tasks


def validate(tasks: list[Task]) -> None:
    ids = [task.id for task in tasks]
    seen: set[str] = set()
    for task_id in ids:
        if task_id in seen:
            raise PlanError(f"{task_id} has more than one row")
        seen.add(task_id)
    for task in tasks:
        if task.status not in STATUSES:
            raise PlanError(f"{task.id}: unknown status {task.status!r}; use one of {', '.join(STATUSES)}")
        for dep in task.deps:
            if dep not in seen:
                raise PlanError(f"{task.id} depends on {dep}, which has no row")
            if dep == task.id:
                raise PlanError(f"{task.id} depends on itself")
    waves(tasks)  # cycles first: they explain more than a status mismatch
    by_id = {task.id: task for task in tasks}
    for task in tasks:
        if task.status != "done":
            continue
        for dep in task.deps:
            if by_id[dep].status not in MERGED:
                raise PlanError(
                    f"{task.id} is done but depends on {dep}, which is {by_id[dep].status}; "
                    "a done task needs its dependencies done or awaiting-acceptance"
                )


def waves(tasks: list[Task]) -> dict[str, int]:
    """Wave of a task: 1 without dependencies, else one more than its latest dependency."""
    by_id = {task.id: task for task in tasks}
    level: dict[str, int] = {}
    visiting: set[str] = set()

    def visit(task_id: str, path: list[str]) -> int:
        if task_id in level:
            return level[task_id]
        if task_id in visiting:
            cycle = path[path.index(task_id):] + [task_id]
            raise PlanError("dependency cycle: " + " -> ".join(cycle))
        visiting.add(task_id)
        deps = by_id[task_id].deps
        value = 1 + max((visit(dep, path + [task_id]) for dep in deps), default=0)
        visiting.discard(task_id)
        level[task_id] = value
        return value

    for task_id in sorted(by_id, key=sort_key):
        visit(task_id, [])
    return level


def _node(task_id: str) -> str:
    return task_id.replace("-", "")


def render_graph(tasks: list[Task]) -> str:
    depended_on = {dep for task in tasks for dep in task.deps}
    lines = ["```mermaid", "flowchart TD"]
    for task in sorted(tasks, key=lambda t: sort_key(t.id)):
        if task.deps:
            sources = " & ".join(_node(dep) for dep in sorted(task.deps, key=sort_key))
            lines.append(f"    {sources} --> {_node(task.id)}")
        elif task.id not in depended_on:
            lines.append(f"    {_node(task.id)}")
    lines.append("```")
    return "\n".join(lines)


def render_waves(tasks: list[Task]) -> str:
    level = waves(tasks)
    groups: dict[int, list[str]] = {}
    for task_id, value in level.items():
        groups.setdefault(value, []).append(task_id)
    lines = ["| Wave | Tasks runnable in parallel |", "|---|---|"]
    for value in sorted(groups):
        lines.append(f"| {value} | {', '.join(sorted(groups[value], key=sort_key))} |")
    return "\n".join(lines)


def _markers(name: str) -> tuple[str, str]:
    return f"<!-- plan-index:{name}:start -->", f"<!-- plan-index:{name}:end -->"


def replace_block(text: str, name: str, body: str) -> str:
    start, end = _markers(name)
    if text.count(start) != 1 or text.count(end) != 1:
        raise PlanError(f"INDEX.md needs exactly one {start} and one {end}")
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    return f"{head}{start}\n<!-- {NOTICE} -->\n{body}\n{end}{tail}"


def generate(text: str) -> str:
    tasks = parse_tasks(text)
    if not tasks:
        raise PlanError("no task rows found")
    validate(tasks)
    text = replace_block(text, GRAPH, render_graph(tasks))
    return replace_block(text, WAVES, render_waves(tasks))


_HEADER = re.compile(r"^(Status|Depends on):[ \t]*(.*)$", re.MULTILINE)


def check_task_files(tasks: list[Task], directory: Path) -> list[str]:
    """Rows whose task file is missing or says something else."""
    problems = []
    for task in tasks:
        path = directory / task.file
        if not path.is_file():
            problems.append(f"{task.id}: {task.file} does not exist")
            continue
        header = dict(_HEADER.findall(path.read_text(encoding="utf-8")))
        status = header.get("Status", "").strip()
        if status != task.status:
            problems.append(f"{task.id}: INDEX says {task.status!r}, {task.file} says {status!r}")
        try:
            deps = _deps(header.get("Depends on", ""))
        except PlanError as error:
            problems.append(f"{task.id}: {task.file}: {error}")
            continue
        if sorted(deps, key=sort_key) != sorted(task.deps, key=sort_key):
            problems.append(
                f"{task.id}: INDEX depends on {', '.join(task.deps) or '—'}, "
                f"{task.file} on {', '.join(deps) or '—'}"
            )
    return problems


def check_acceptance(tasks: list[Task], directory: Path) -> list[str]:
    """`awaiting-acceptance` tasks that the acceptance matrix does not name."""
    waiting = [task.id for task in tasks if task.status == "awaiting-acceptance"]
    path = directory / ACCEPTANCE
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    return [
        f"{task_id} is awaiting-acceptance but {ACCEPTANCE} has no row for it"
        for task_id in waiting
        if f"[{task_id}]" not in text
    ]


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail instead of writing when stale")
    parser.add_argument("--index", type=Path, default=DEFAULT_INDEX)
    args = parser.parse_args(argv)
    try:
        text = args.index.read_text(encoding="utf-8")
        updated = generate(text)
        tasks = parse_tasks(text)
        problems = check_task_files(tasks, args.index.parent)
        problems += check_acceptance(tasks, args.index.parent)
    except PlanError as error:
        print(f"plan-index: {error}", file=sys.stderr)
        return 1
    for problem in problems:
        print(f"plan-index: {problem}", file=sys.stderr)
    if updated != text:
        if args.check:
            print("plan-index: the graph or waves in INDEX.md are stale; run `just plan-index`",
                  file=sys.stderr)
            return 1
        args.index.write_text(updated, encoding="utf-8")
        print(f"plan-index: updated {args.index}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
